package io.github.search5.hg4j.api;

import io.github.search5.hg4j.dirstate.Dirstate;
import io.github.search5.hg4j.errors.HgLockException;
import io.github.search5.hg4j.errors.HgValidationException;
import io.github.search5.hg4j.lib.HgLock;
import io.github.search5.hg4j.lib.HgRepository;
import io.github.search5.hg4j.shape.Fingerprint;
import io.github.search5.hg4j.shape.Shape;
import io.github.search5.hg4j.shape.ShapeConfigStore;
import io.github.search5.hg4j.shape.ShapeNames;
import io.github.search5.hg4j.shape.ShardTreeNode;
import io.github.search5.hg4j.shape.StoreShards;
import io.github.search5.hg4j.util.SafeFileIO;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Set;
import java.util.TreeSet;

/**
 * {@code hg admin::narrow-server} and {@code admin::narrow-client} ({@code admin_commands.py}): the administration of the shards and
 * shapes of a server repository. See {@code llm-wiki/concepts/store-shapes.md}, sections 10 and 11, for the analysis.
 *
 * <p>Locks, as hg takes them: updating the config holds the {@code store-shapes-lock} (not waiting) for the whole of the operation and the
 * store lock only for the write ({@code with repo.store_shapes_lock(wait=False): ... with repo.lock():}); clearing the saved configs holds
 * both at once, the shapes lock first. The read-only commands take no lock and only warn when an update is in progress.</p>
 */
public final class NarrowServerAdmin {

    /** The three {@code override-*} checks of {@code --shape-update}. */
    public record UpdateOptions(boolean overrideReshapeAndReshardCheck, boolean overrideFingerprintChangeCheck, boolean overrideSavedConfigsCheck) {
        public static UpdateOptions strict() {
            return new UpdateOptions(false, false, false);
        }
    }

    /** The header put in front of a {@code server-shapes} file this command writes. */
    public static final String HEADER = "# Do not edit this file by hand!\n"
            + "# Use `hg admin::narrow-server --shape-update` instead,\n"
            + "# which will ensure the update is made safely.\n";

    private final HgRepository repository;
    private final List<String> warnings = new ArrayList<>();

    public NarrowServerAdmin(HgRepository repository) {
        this.repository = repository;
    }

    /** What the last call warned about (hg's {@code ui.warn}). */
    public List<String> getWarnings() {
        return warnings;
    }

    private void checkServerRepository() throws IOException {
        for (File requires : List.of(new File(repository.getHgDir(), "requires"), new File(repository.getStoreDir(), "requires"))) {
            if (requires.isFile() && Files.readString(requires.toPath()).lines().anyMatch(l -> l.trim().equals("narrowhg-experimental"))) {
                throw new HgValidationException("repo is narrowed, this is a server command");
            }
        }
    }

    private StoreShards storeShards() throws IOException {
        checkServerRepository();
        warnings.clear();
        String holder = repository.readStoreShapesLockHolder();
        if (holder != null) {
            warnings.add("warning: store shapes are currently being updated (lock held by " + holder + ")\n");
        }
        return StoreShards.fromRepository(repository);
    }

    // ---------------------------------------------------------------- read only subcommands

    /** {@code --shape-fingerprints}: {@code <fingerprint> <names>} for every shape. */
    public List<String> shapeFingerprints() throws IOException {
        List<String> out = new ArrayList<>();
        for (Shape shape : storeShards().allShapes()) {
            out.add(shape.storeFingerprint().toText() + " " + String.join(",", shape.names()));
        }
        return out;
    }

    /** {@code --store-shards}: the id of every shard, then {@code  read-write-access=a,b} when it has some. */
    public List<String> storeShardsListing() throws IOException {
        List<String> out = new ArrayList<>();
        for (StoreShards.ShardListing listing : storeShards().listShards()) {
            out.add(listing.shardId().toText() + (listing.readWriteAccess() == null ? ""
                    : " read-write-access=" + String.join(",", listing.readWriteAccess())));
        }
        return out;
    }

    private Shape shapeOf(String names) throws IOException {
        List<String> parsed = ShapeNames.parse(names);
        try {
            return storeShards().shape(parsed);
        } catch (io.github.search5.hg4j.shape.ShapeException e) {
            if (e.kind() == io.github.search5.hg4j.shape.ShapeException.Kind.UNKNOWN_PROFILE) {
                throw new HgValidationException("shape '" + e.subject() + "' not found");
            }
            throw e;
        }
    }

    /** {@code --shape-patterns NAMES}: {@code inc:/path} and {@code exc:/path}, in zero path order. */
    public List<String> shapePatterns(String names) throws IOException {
        ShardTreeNode.Patterns patterns = shapeOf(names).patterns();
        record Line(String path, boolean included) {
        }
        List<Line> lines = new ArrayList<>();
        patterns.includes().forEach(p -> lines.add(new Line(p, true)));
        patterns.excludes().forEach(p -> lines.add(new Line(p, false)));
        lines.sort(Comparator.comparing(l -> {
            try {
                return new String(ShardTreeNode.zeroPath(l.path()), StandardCharsets.ISO_8859_1);
            } catch (HgValidationException e) {
                throw new IllegalStateException(e);
            }
        }));
        List<String> out = new ArrayList<>();
        for (Line line : lines) {
            out.add((line.included() ? "inc" : "exc") + ":/" + line.path());
        }
        return out;
    }

    /** {@code --shape-narrow-patterns NAMES}: the legacy {@code [include]} / {@code [exclude]} sections, without the root. */
    public List<String> shapeNarrowPatterns(String names) throws IOException {
        ShardTreeNode.Patterns patterns = shapeOf(names).patterns();
        List<String> includes = patterns.includes().stream().filter(p -> !p.isEmpty()).toList();
        List<String> excludes = patterns.excludes().stream().filter(p -> !p.isEmpty()).toList();
        List<String> out = new ArrayList<>();
        if (!includes.isEmpty()) {
            out.add("[include]");
            includes.forEach(p -> out.add("path:" + p));
        }
        if (!excludes.isEmpty()) {
            out.add("[exclude]");
            excludes.forEach(p -> out.add("path:" + p));
        }
        return out;
    }

    /**
     * {@code --shape-files NAMES} / {@code --shape-files-hidden NAMES}: the filelogs of the store that the shape covers, sorted; with
     * {@code hiddenOnly} only those that are not in the working copy.
     */
    public List<String> shapeFiles(String names, boolean hiddenOnly) throws IOException {
        Shape shape = shapeOf(names);
        io.github.search5.hg4j.match.Matcher matcher = shape.matcher();
        Set<String> known = new TreeSet<>();
        for (java.util.Map.Entry<String, Dirstate.Entry> e : repository.getDirstate().getEntries().entrySet()) {
            if (e.getValue().getState() != 'r' && matcher.matches(e.getKey())) {
                known.add(e.getKey());
            }
        }
        Set<String> files = new TreeSet<>();
        File fncache = new File(repository.getStoreDir(), "fncache");
        if (fncache.isFile()) {
            for (String line : Files.readAllLines(fncache.toPath(), StandardCharsets.ISO_8859_1)) {
                if (line.startsWith("data/") && line.endsWith(".i")) {
                    String path = line.substring("data/".length(), line.length() - ".i".length());
                    if (matcher.matches(path)) {
                        files.add(path);
                    }
                }
            }
        }
        List<String> out = new ArrayList<>();
        for (String file : files) {
            if (!(hiddenOnly && known.contains(file))) {
                out.add(file);
            }
        }
        return out;
    }

    // ---------------------------------------------------------------- updating the config

    private static String quoteNames(List<String> names) {
        List<String> quoted = new ArrayList<>();
        names.forEach(n -> quoted.add("\"" + n + "\""));
        return String.join(", ", quoted);
    }

    /**
     * {@code _validate_shape_update}: refuses an update that redefines an existing shape, reshapes and reshards at once, or reshapes
     * while previous configs are still saved (each unless its override is set).
     */
    static void validateUpdate(StoreShards old, StoreShards updated, List<String> savedConfigs, UpdateOptions options) throws IOException {
        if (!options.overrideFingerprintChangeCheck()) {
            List<String> redefined = old.redefinedShapes(updated);
            if (!redefined.isEmpty()) {
                throw new HgValidationException("won't change the fingerprint of existing shapes: " + quoteNames(redefined)
                        + "\n(hint: see 'hg help \"narrow.updating the shapes config\"' for how to publish this as a new shape)");
            }
        }
        List<String> shapes = old.changedShapes(updated);
        if (!options.overrideReshapeAndReshardCheck()) {
            List<String> shards = old.changedShards(updated);
            if (!shapes.isEmpty() && !shards.isEmpty()) {
                throw new HgValidationException("cannot reshape and reshard in the same update\nshapes changed: " + quoteNames(shapes)
                        + "\nshards changed: " + quoteNames(shards)
                        + "\n(hint: see 'hg help \"narrow.updating the shapes config\"' for how to split this in two updates)");
            }
        }
        if (!options.overrideSavedConfigsCheck()) {
            if (!shapes.isEmpty() && !savedConfigs.isEmpty()) {
                throw new HgValidationException("cannot reshape yet: " + savedConfigs.size()
                        + " previous server-shapes still saved\nshapes changed: " + quoteNames(shapes)
                        + "\n(hint: see 'hg help \"narrow.updating the shapes config\"' for how to clear the saved configs)");
            }
        }
    }

    /**
     * {@code --shape-update}: replaces the {@code server-shapes} file.
     *
     * <p>Order of locks and work, as {@code admin_commands._shape_update}: the shapes lock (no waiting) -> read the old config -> parse and
     * validate the new one (a bad document aborts here, nothing written) -> the store lock -> save the old config when shards changed ->
     * write atomically.</p>
     */
    public void shapeUpdate(byte[] newContents, UpdateOptions options) throws IOException, HgLockException {
        checkServerRepository();
        try (HgLock shapesLock = repository.lockStoreShapes(0)) {
            StoreShards old = StoreShards.fromRepository(repository);
            File shapesFile = new File(repository.getStoreDir(), StoreShards.SHAPES_FILE);
            byte[] oldContents = shapesFile.isFile() ? Files.readAllBytes(shapesFile.toPath()) : new byte[0];
            StoreShards updated = StoreShards.fromBytes(newContents);
            validateUpdate(old, updated, ShapeConfigStore.previousConfigs(repository), options);
            byte[] contents = newContents;
            if (!new String(newContents, StandardCharsets.UTF_8).startsWith(HEADER)) {
                contents = (HEADER + new String(newContents, StandardCharsets.UTF_8)).getBytes(StandardCharsets.UTF_8);
            }
            try (HgLock lock = repository.lockStoreWithoutRecovery(repository.resolvePushLockTimeoutMs())) {
                List<String> changedShards = old.changedShards(updated);
                if (oldContents.length > 0 && !changedShards.isEmpty()) {
                    ShapeConfigStore.savePreviousConfig(repository, oldContents);
                }
                SafeFileIO.writeAtomic(shapesFile, contents);
            }
        }
    }

    /**
     * {@code --shape-clear-previous}: removes the saved previous configs, which can be done once the sharded bundles for the current
     * config are generated and advertised. Holds the shapes lock (no waiting) and the store lock together, the shapes lock first.
     *
     * @return {@code cleared N saved server-shapes}
     */
    public String shapeClearPrevious() throws IOException, HgLockException {
        checkServerRepository();
        try (HgLock shapesLock = repository.lockStoreShapes(0); HgLock lock = repository.lockStoreWithoutRecovery(repository.resolvePushLockTimeoutMs())) {
            return "cleared " + ShapeConfigStore.clearPreviousConfigs(repository).size() + " saved server-shapes\n";
        }
    }

    // ---------------------------------------------------------------- admin::narrow-client

    /** {@code admin::narrow-client --store-fingerprint}: the fingerprint of the store narrowspec of a narrow clone. */
    public static String storeFingerprint(Set<String> includes, Set<String> excludes) throws HgValidationException {
        Set<String> inc = new java.util.LinkedHashSet<>();
        includes.forEach(p -> inc.add(p.startsWith("path:") ? p.substring(5) : p));
        Set<String> exc = new java.util.LinkedHashSet<>();
        excludes.forEach(p -> exc.add(p.startsWith("path:") ? p.substring(5) : p));
        Fingerprint fingerprint = ShardTreeNode.fromPatterns(inc, exc).fingerprint();
        return fingerprint.toText() + "\n";
    }
}
